// Types and helpers shared by the generators. The catalog itself lives in the private okdata
// repository; these interfaces describe only the parts the public files are built from.

export type Lang = 'en' | 'zh';
export type Text = Record<Lang, string>;

export interface Param {
  name: string;
  type: 'string' | 'integer' | 'boolean' | 'string[]';
  required: boolean;
  description: Text;
  enum?: string[];
  default?: string | number | boolean;
  example?: string | number | boolean;
}

export interface Endpoint {
  id: string;
  platform: string;
  method: 'GET' | 'POST';
  object: 'post' | 'account' | 'comment' | 'trend' | 'transcript';
  list: boolean;
  pageSize?: number;
  unit: 'call' | 'item';
  price: string;
  maxCharge: string;
  title: Text;
  summary: Text;
  params: Param[];
  jobs: string[];
  status: 'beta' | 'stable';
}

export interface Platform {
  id: string;
  name: Text;
  summary: Text;
  region: 'cn' | 'global';
}

export interface Catalog {
  revision: string;
  priceBook: string;
  baseUrl: string;
  platforms: Platform[];
  endpoints: Endpoint[];
}

export interface FieldDoc {
  name: string;
  type: 'string' | 'integer' | 'number' | 'boolean' | 'object' | 'string[]' | 'ref' | 'ref[]';
  ref?: string;
  nullable: boolean;
  optional?: boolean;
  enum?: string[];
  description: Text;
}

export interface SiteInfo {
  brand: string;
  siteUrl: string;
  apiUrl: string;
  mcpUrl: string;
  keyPrefix: string;
  envVar: string;
}

/** What the generators get: the catalog, the site config and the private repo's generate module. */
export interface Source {
  catalog: Catalog;
  site: SiteInfo;
  gen: Record<string, (...args: never[]) => unknown> & {
    objectFields: Record<string, FieldDoc[]>;
    OBJECT_KINDS: readonly Endpoint['object'][];
    jobLabels: Record<string, Text>;
  };
  pathOf: (e: Pick<Endpoint, 'id'>) => string;
}

/** One output file: a path relative to the repository root and its full text. */
export type Files = Map<string, string>;

export const GENERATED_NOTE = 'Generated by scripts/sync.ts from the okdata catalog. Do not edit by hand.';

/** Sub-objects come first so every reference points backwards in the generated code. */
export const MODEL_ORDER = ['AccountRef', 'Metrics', 'Segment', 'post', 'account', 'comment', 'trend', 'transcript'] as const;

export const modelName = (name: string): string => name.charAt(0).toUpperCase() + name.slice(1);

/** Parameters every endpoint shares; SDKs treat them as options rather than per-endpoint inputs. */
export const SHARED_PARAMS = new Set(['view', 'fields']);

/** "douyin.videos.comments.list" -> namespace ["douyin", "videos", "comments"] + action "list". */
export function splitId(id: string): { namespace: string[]; action: string } {
  const parts = id.split('.');
  const action = parts.pop();
  if (!action || parts.length === 0) throw new Error(`Endpoint id "${id}" needs at least platform.action`);
  return { namespace: parts, action };
}

export interface NamespaceNode {
  path: string[];
  children: Map<string, NamespaceNode>;
  endpoints: Endpoint[];
}

/** Endpoints grouped into nested namespaces, in catalog order. */
export function namespaceTree(endpoints: Endpoint[]): NamespaceNode {
  const root: NamespaceNode = { path: [], children: new Map(), endpoints: [] };
  for (const e of endpoints) {
    const { namespace } = splitId(e.id);
    let node = root;
    for (const part of namespace) {
      const next = node.children.get(part) ?? { path: [...node.path, part], children: new Map(), endpoints: [] };
      node.children.set(part, next);
      node = next;
    }
    node.endpoints.push(e);
  }
  return root;
}

/** Endpoints with optional id and url take exactly one of the two. */
export const needsIdOrUrl = (e: Endpoint): boolean => {
  const id = e.params.find((p) => p.name === 'id');
  const url = e.params.find((p) => p.name === 'url');
  return Boolean(id && url && !id.required && !url.required);
};

export const docsUrl = (site: SiteInfo, e: Endpoint, lang: Lang = 'en'): string =>
  `${site.siteUrl}${lang === 'zh' ? '/zh' : ''}/apis/${e.id.split('.').join('/')}/`;

/** "$0.02 per call" or "$0.058 per item, at most $0.58 per call". */
export function priceText(e: Endpoint): string {
  return e.unit === 'item'
    ? `$${e.price} per item returned, at most $${e.maxCharge} per call`
    : `$${e.price} per call`;
}

export function priceTextZh(e: Endpoint): string {
  return e.unit === 'item' ? `每条 $${e.price}，每次最多 $${e.maxCharge}` : `每次 $${e.price}`;
}

/** A parameter's English description; drops "Give id or url." where the endpoint takes no url. */
export function paramDescription(e: Endpoint, p: Param): string {
  const text = p.description.en;
  return needsIdOrUrl(e) ? text : text.replace(/\s*Give id or url\.\s*/, ' ').trim();
}
